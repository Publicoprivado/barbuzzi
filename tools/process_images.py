"""Resize source images into web-ready WebP files and regenerate assets/js/images.js.

Source layout (outside the site, so deploys stay light):
    ../source-images/<project-slug>/01.jpg, 02.jpg, ...
Files are used in filename order. The slug must match a project in assets/js/data.js.

Usage (needs Pillow):
    python tools/process_images.py            # only new images
    python tools/process_images.py --force    # rebuild everything
"""
import json
import sys
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT.parent / "source-images"
OUT = ROOT / "assets" / "img"
INDEX = ROOT / "assets" / "js" / "images.js"
WIDTHS = [480, 960, 1600, 2400]
QUALITY = 80
EXTS = {".jpg", ".jpeg", ".png", ".webp", ".tif", ".tiff"}


def process(src: Path, dest_dir: Path, stem: str, force: bool):
    im = Image.open(src)
    im = ImageOps.exif_transpose(im).convert("RGB")
    w, h = im.size
    top = min(w, WIDTHS[-1])
    # Skip steps within 15% of the largest size — they'd be near-duplicates.
    sizes = [x for x in WIDTHS if x < top * 0.85] + [top]
    for size in sizes:
        out = dest_dir / f"{stem}-{size}.webp"
        if out.exists() and not force:
            continue
        resized = im if size == w else im.resize((size, round(h * size / w)), Image.LANCZOS)
        resized.save(out, "WEBP", quality=QUALITY, method=6)
    r, g, b = im.resize((1, 1), Image.BOX).getpixel((0, 0))
    return {"f": stem, "w": w, "h": h, "c": f"#{r:02x}{g:02x}{b:02x}", "s": sizes}


def main():
    force = "--force" in sys.argv
    index = {}
    for project in sorted(p for p in SOURCE.iterdir() if p.is_dir()):
        files = sorted(f for f in project.iterdir() if f.suffix.lower() in EXTS)
        if not files:
            continue
        dest = OUT / project.name
        dest.mkdir(parents=True, exist_ok=True)
        index[project.name] = [process(f, dest, f"{i:02d}", force) for i, f in enumerate(files, 1)]
        print(f"{project.name}: {len(files)} image(s)")
    rows = []
    for slug, images in index.items():
        lines = ",\n".join(f"    {json.dumps(im, separators=(',', ':'))}" for im in images)
        rows.append(f"  {json.dumps(slug)}: [\n{lines},\n  ]")
    INDEX.write_text(
        "// Generated by tools/process_images.py — do not edit by hand.\n"
        "// f: file stem, w/h: original size, c: average colour, s: generated widths\n"
        "export const IMAGES = {\n" + ",\n".join(rows) + ",\n};\n",
        encoding="utf-8",
    )
    # Drop generated sizes that are no longer referenced (e.g. after --force).
    for slug, images in index.items():
        keep = {f"{im['f']}-{s}.webp" for im in images for s in im["s"]}
        for f in (OUT / slug).glob("*.webp"):
            if f.name not in keep:
                f.unlink()
    print(f"wrote {INDEX.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
